"""Write the LaTeX tables of the second round from Analysis/results, so the report never has typed-in numbers.
Outputs (Report/tables/): prl.tex, nature.tex, if_grid.tex, if10_journals.tex  (each is \\input by report.tex)
OpenAlex lost the maths in some PRL titles (e.g. 'JeffDescription ... Insulatorα−RuCl3'), so those titles are taken
from Crossref (the publisher's record) and written in LaTeX in TITLE_FIX, keyed by DOI.
usage: python make_tables.py   (after Analysis/scripts/stats_if_authors.py)"""
import os, csv

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "..", "Analysis", "results")
OUT = os.path.join(HERE, "tables")
os.makedirs(OUT, exist_ok=True)
SHORT = {"IIT Kharagpur": "KGP", "IIT Roorkee": "Roork."}

TITLE_FIX = {   # Crossref titles, MathML written as LaTeX
    "10.1103/physrevlett.131.056202": r"Anomalous Reentrant 5/2 Quantum Hall Phase at Moderate Landau-Level-Mixing Strength",
    "10.1103/physrevlett.132.029602": r"Das \textit{et al.}\ Reply (reply to a comment)",
    "10.1103/physrevlett.132.106501": r"Fractional Quantum Hall States of the $\mathcal{A}$ Phase in the Second Landau Level",
    "10.1103/physrevlett.117.126403": r"$J_{\mathrm{eff}}$ Description of the Honeycomb Mott Insulator $\alpha$-RuCl$_3$",
    "10.1103/physrevlett.116.072501": r"Single and Double Beta-Decay $Q$ Values among the Triplet $^{96}$Zr, $^{96}$Nb, and $^{96}$Mo",
    "10.1103/physrevlett.118.151802": r"Measurement of the Neutrino Mixing Angle $\theta_{23}$ in NOvA",
    "10.1103/physrevlett.123.262701": r"Discovery of an Exceptionally Strong $\beta$-Decay Transition of $^{20}$F and Implications for the Fate of Intermediate-Mass Stars",
    "10.1103/s7hr-y7zq": r"Probing the Shell Effects on Fission: The New Superheavy Nucleus $^{257}$Sg",
}


def tex(s):
    """Escape plain text for LaTeX."""
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"), ("_", r"\_"),
                 ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\textasciicircum{}"), ("–", "--"), ("—", "---")):
        s = s.replace(a, b)
    return s


def rows(name):
    with open(os.path.join(RES, name), encoding="utf-8-sig", newline="") as fh:
        return list(csv.DictReader(fh))


def write(name, lines):
    with open(os.path.join(OUT, name), "w", encoding="utf-8") as fh:
        # \bottomrule sits in the file: after an \input, LaTeX would see it outside the table rows (Misplaced \noalign)
        fh.write("% generated by Report/make_tables.py from Analysis/results, do not edit by hand\n" + "\n".join(lines)
                 + "\n\\bottomrule\n")


def faculty(s):
    names = [n.strip() for n in s.split(";") if n.strip()]
    return ", ".join("Dr.~" + tex(n) for n in names) if names else "(institute)"


def main():
    # PRL papers
    out = []
    for r in rows("prl_papers.csv"):
        doi = r["doi"].replace("https://doi.org/", "")
        title = TITLE_FIX.get(doi, tex(r["title"]))
        out.append(f"{SHORT[r['institution']]} & {r['year']} & {title} & {faculty(r['faculty'])} & {r['authors']} & {r['citations']} \\\\")
    write("prl.tex", out)

    # Nature journals
    out = []
    for r in rows("nature_journals_if.csv"):
        out.append(f"{tex(r['journal'])} & {float(r['if_openalex']):.1f} & {r['IIT Kharagpur']} & {r['IIT Roorkee']} \\\\")
    write("nature.tex", out)

    # the class-notes grid (journal papers)
    out = []
    g = rows("q1_if_author_grid.csv")
    for inst in ("IIT Kharagpur", "IIT Roorkee"):
        out.append(f"\\multicolumn{{6}}{{@{{}}l}}{{\\emph{{{inst}}}}} \\\\")
        for r in (x for x in g if x["institution"] == inst):
            label = r["row"].replace(">", "$>$")
            out.append(f"{label} & {int(r['papers']):,} & {int(r['fewer than 10']):,} & {int(r['exactly 10']):,} & "
                       f"{int(r['more than 10']):,} & {100 * float(r['share_more_than_10']):.1f}\\% \\\\")
        if inst == "IIT Kharagpur":
            out.append("\\midrule")
    write("if_grid.tex", out)

    # journals of the IF > 10 papers with fewer than 10 authors (top 5 per IIT)
    out = []
    j = rows("if10_small_team_journals.csv")
    for inst in ("IIT Kharagpur", "IIT Roorkee"):
        sel = [x for x in j if x["institution"] == inst]
        total = sum(int(x["papers_fewer_than_10_authors"]) for x in sel)
        out.append(f"\\multicolumn{{3}}{{@{{}}l}}{{\\emph{{{inst}}} ({total:,} papers in {len(sel)} journals)}} \\\\")
        for x in sel[:5]:
            out.append(f"{tex(x['journal'])} & {float(x['if_openalex']):.1f} & {x['papers_fewer_than_10_authors']} \\\\")
        if inst == "IIT Kharagpur":
            out.append("\\midrule")
    write("if10_journals.tex", out)
    print("tables written to", OUT)


if __name__ == "__main__":
    main()
